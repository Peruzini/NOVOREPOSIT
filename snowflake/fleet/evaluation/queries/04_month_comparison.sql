WITH periods AS (
 SELECT
   SUM(CASE WHEN DATA >= '2026-01-01' AND DATA < '2026-02-01' THEN PRODUCAO_TON END) AS ATUAL,
   SUM(CASE WHEN DATA >= '2025-12-01' AND DATA < '2026-01-01' THEN PRODUCAO_TON END) AS ANTERIOR
 FROM FLEET_DAILY
)
SELECT ATUAL, ANTERIOR, (ATUAL - ANTERIOR) / NULLIF(ANTERIOR, 0) AS VARIACAO_MOM
FROM periods;

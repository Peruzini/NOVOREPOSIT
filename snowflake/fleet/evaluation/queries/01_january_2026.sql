SELECT
  SUM(PRODUCAO_TON) AS PRODUCAO_TON,
  SUM(HORAS_OPERACAO) AS HORAS_OPERACAO,
  SUM(HORAS_MANUTENCAO) AS HORAS_MANUTENCAO,
  SUM(HORAS_CORRETIVAS) AS HORAS_CORRETIVAS,
  COALESCE(SUM(FALHAS), 0) AS FALHAS,
  SUM(CUSTO_MANUTENCAO + CUSTO_COMBUSTIVEL) AS CUSTO_TOTAL,
  SUM(CUSTO_MANUTENCAO + CUSTO_COMBUSTIVEL) / NULLIF(SUM(PRODUCAO_TON), 0) AS CUSTO_POR_TONELADA,
  (SUM(HORAS_CALENDARIO) - SUM(HORAS_MANUTENCAO)) / NULLIF(SUM(HORAS_CALENDARIO), 0) AS DISPONIBILIDADE,
  SUM(HORAS_OPERACAO) / NULLIF(SUM(HORAS_CALENDARIO) - SUM(HORAS_MANUTENCAO), 0) AS UTILIZACAO,
  SUM(HORAS_CORRETIVAS) / NULLIF(SUM(FALHAS), 0) AS MTTR,
  SUM(HORAS_OPERACAO) / NULLIF(SUM(FALHAS), 0) AS MTBF,
  SUM(PRODUCAO_TON) / NULLIF(SUM(META_PRODUCAO_TON), 0) AS ADERENCIA_META
FROM FLEET_DAILY
WHERE DATA >= '2026-01-01' AND DATA < '2026-02-01';
